module Services.RetroAvatar

// =============================================================================
// Build-time "make it look like 1993" avatar generator.
//
// Turns the full-color site avatar into a Doom-style retro portrait using the
// classic VGA Mode 13h idiom described in
// https://staniks.github.io/articles/catlantean-3d-blog-1/ :
//   low resolution  +  a tightly restricted 256-color palette  +  palette
//   quantization  =  that crispy, deliberate, chunky look.
//
// Pipeline (see `generateDoomAvatar`):
//   1. decode source PNG (SkiaSharp, same cross-platform decoder QRStyled uses)
//   2. optional mild center-crop to tighten the framing on the face
//   3. downscale to a small square grid  -> pixelation
//   4. quantize every pixel to the nearest color in the authentic Doom PLAYPAL
//      palette (256 colors), using a perceptual "redmean" RGB distance so
//      shading doesn't drift toward flat grey (a failure mode the article
//      explicitly calls out for plain Euclidean distance)
//   5. upscale nearest-neighbor back to the output size -> hard pixel blocks
//   6. encode PNG
//
// No new dependencies: SkiaSharp is already referenced (with Linux + Win32
// native assets), so this runs in the GitHub Actions Linux build too.
//
// The original avatar is never modified; this only *produces* a new file.
// Tunables live in `Options` / `defaultOptions` so the retro look can be
// recalibrated with a one-line change and a rebuild (no tokens spent).
// =============================================================================

