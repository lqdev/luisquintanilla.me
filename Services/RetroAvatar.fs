/// The 256-color Doom palette as (R, G, B) triples, parsed once at startup.
let doomPalette : (byte * byte * byte)[] =
    let bytes =
        Regex.Matches(playpalText, "0x([0-9a-fA-F]{2})")
        |> Seq.cast<Match>
        |> Seq.map (fun m -> Convert.ToByte(m.Groups.[1].Value, 16))
        |> Seq.toArray
    if bytes.Length <> 768 then
        failwithf "RetroAvatar: expected 768 palette bytes, got %d" bytes.Length
    Array.init 256 (fun i -> bytes.[i * 3], bytes.[i * 3 + 1], bytes.[i * 3 + 2])

/// Tunable knobs for the retro look. Change one line, rebuild, done.
type Options =
    { /// Downscaled grid the source is reduced to before quantization.
      /// Smaller = chunkier / more retro. 400 / GridSize = block size.
      GridSize: int
      /// Final square PNG size (matches the original avatar for a drop-in).
      OutputSize: int
      /// Fraction trimmed off each edge before pixelating, to tighten the
      /// crop onto the face (Doom mugshot framing). 0.0 disables cropping.
      CropFraction: float
      /// Ordered (Bayer 4x4) dithering before quantization. Off by default for
      /// a cleaner, flatter mugshot; on trades banding for stipple.
      Dither: bool }

let defaultOptions =
    { GridSize = 48
      OutputSize = 400
      CropFraction = 0.06
      Dither = false }

// Bayer 4x4 threshold matrix (values 0..15) for optional ordered dithering.
let private bayer4 =
    [| [| 0; 8; 2; 10 |]
       [| 12; 4; 14; 6 |]
       [| 3; 11; 1; 9 |]
       [| 15; 7; 13; 5 |] |]

let inline private clampByte (v: float) : byte =
    byte (max 0.0 (min 255.0 v))

/// Nearest palette color using a "redmean" weighted RGB distance, which tracks
/// human color perception far better than plain Euclidean (whose bias toward
/// grey the source article specifically warns about).
let private nearestPaletteColor (r: byte) (g: byte) (b: byte) =
    let rf = float r
    let gf = float g
    let bf = float b
    let mutable best = 0
    let mutable bestDist = Double.MaxValue
    for i in 0 .. 255 do
        let (pr, pg, pb) = doomPalette.[i]
        let rmean = (rf + float pr) / 2.0
        let dr = rf - float pr
        let dg = gf - float pg
        let db = bf - float pb
        let dist =
            (2.0 + rmean / 256.0) * dr * dr
            + 4.0 * dg * dg
            + (2.0 + (255.0 - rmean) / 256.0) * db * db
        if dist < bestDist then
            bestDist <- dist
            best <- i
    doomPalette.[best]

/// Produce a Doom-palette, pixelated version of `srcPath` at `outPath`.
/// Returns `outPath`. The source file is only read, never modified.
let generateDoomAvatar (srcPath: string) (outPath: string) (opts: Options) =
    let outDir = Path.GetDirectoryName(outPath)
    if not (String.IsNullOrEmpty outDir) && not (Directory.Exists outDir) then
        Directory.CreateDirectory(outDir) |> ignore

    use src = SKBitmap.Decode(srcPath)
    if isNull src then
        failwithf "RetroAvatar.generateDoomAvatar: failed to decode '%s'" srcPath

    // 1. Optional mild center-crop for Doom mugshot framing.
    let cropped =
        if opts.CropFraction <= 0.0 then
            src
        else
            let dx = int (float src.Width * opts.CropFraction)
            let dy = int (float src.Height * opts.CropFraction)
            let rect = SKRectI(dx, dy, src.Width - dx, src.Height - dy)
            let sub = new SKBitmap(rect.Width, rect.Height)
            if src.ExtractSubset(sub, rect) then sub
            else
                sub.Dispose()
                src

    // 2. Downscale to the pixel grid (linear averaging -> clean pixelation).
    let gridInfo =
        SKImageInfo(opts.GridSize, opts.GridSize, SKColorType.Rgba8888, SKAlphaType.Unpremul)
    use small = new SKBitmap(gridInfo)
    let downSampling = SKSamplingOptions(SKFilterMode.Linear, SKMipmapMode.None)
    if not (cropped.ScalePixels(small, downSampling)) then
        failwith "RetroAvatar.generateDoomAvatar: downscale failed"

    // 3. Quantize each pixel to the nearest Doom palette color (optional dither).
    for y in 0 .. opts.GridSize - 1 do
        for x in 0 .. opts.GridSize - 1 do
            let c = small.GetPixel(x, y)
            let r, g, b =
                if opts.Dither then
                    let t = (float bayer4.[y % 4].[x % 4] / 16.0 - 0.5) * 40.0
                    clampByte (float c.Red + t), clampByte (float c.Green + t), clampByte (float c.Blue + t)
                else
                    c.Red, c.Green, c.Blue
            let (pr, pg, pb) = nearestPaletteColor r g b
            small.SetPixel(x, y, SKColor(pr, pg, pb, c.Alpha))

    // 4. Upscale nearest-neighbor -> hard, chunky retro pixels.
    let outInfo =
        SKImageInfo(opts.OutputSize, opts.OutputSize, SKColorType.Rgba8888, SKAlphaType.Unpremul)
    use big = new SKBitmap(outInfo)
    let upSampling = SKSamplingOptions(SKFilterMode.Nearest, SKMipmapMode.None)
    if not (small.ScalePixels(big, upSampling)) then
        failwith "RetroAvatar.generateDoomAvatar: upscale failed"

    // 5. Encode PNG.
    use image = SKImage.FromBitmap(big)
    use data = image.Encode(SKEncodedImageFormat.Png, 100)
    use fs = File.Create(outPath)
    data.SaveTo(fs)

    if not (obj.ReferenceEquals(cropped, src)) then cropped.Dispose()
    outPath
